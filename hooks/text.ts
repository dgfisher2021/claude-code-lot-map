// Every word the map shows, in each language it speaks.
// A new language is one more table here and one more value of `language` in plugin.json.
import type { StationId } from '../types'

export type Strings = {
  title: string
  command: string
  opened: string
  cannotOpen: (reason: string) => string
  stations: Record<StationId, string>
  newMessage: string
  answerReady: string
  turnAborted: string
  step: (n: number) => string
  subagent: string
  compacting: string
  addedContext: (when: string) => string
  addedMemory: (when: string) => string
  toMessage: string
  atStart: string
  records: (n: number, shown: string) => string
  stopped: (tool: string) => string
  askedPermission: (tool: string) => string
  checkBefore: (tool: string) => string
  running: string
  nothingYet: string
  noCounts: string
  /** In a terminal pane too narrow for the map: how wide it would need to be. */
  tooNarrow: (columns: number) => string
  /** After `/lot-map window`: the map opened in a pane of its own, already open, or how to open it by hand. */
  windowOpened: string
  windowOpen: string
  windowByHand: (command: string) => string
  idle: string
  /** The word under the core: what the session is doing. Fourteen characters at most. */
  states: { idle: string; thinking: string; running: string; waiting: string; compacting: string; done: string }
  /** `/workmap help`, and `?` in the window: what the map's marks mean. Eight lines. */
  legend: string[]
  /** A station's title, for hovering in the app: its calls, its errors and its refusals. */
  callsHere: (n: number) => string
  errorsHere: (n: number) => string
  refusedHere: (n: number) => string
  context: string
  andMore: (n: number) => string
  webSearch: string
  artifact: string
  workflow: string
  skill: string
  loadingTools: string
  questionForYou: string
  planForYou: string
  /** The top line while Claude waits on the person, and after an answer: what it waits for or since when, and how long. */
  waitingFor: (label: string, since: string) => string
  yourTurn: (since: string) => string
  /** With `notify` on: a wait, and a finished turn. */
  notifyWaiting: (label: string) => string
  notifyDone: string
  fileForYou: string
  ms: (n: number) => string
  seconds: (s: string) => string
  minutes: (m: number, s: number) => string
  /** A time since, once it passes a minute: whole minutes. */
  wholeMinutes: (m: number) => string
  /** A failed shell command's exit code, in its row. */
  exitCode: (n: number) => string
  /** Claude's plan over the rows: how many of how many tasks are done, and the calls a finished task took. */
  planHeader: (done: number, total: number) => string
  planCalls: (n: number) => string
}

